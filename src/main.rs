use std::io::{self, Write};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Mode {
    Move,
    Visual,
    Line,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct Action(Mode, &'static str, &'static str);

const KEYS: &[&str] = &[
    "h", "j", "k", "l", "left", "down", "up", "right", "pageup", "pagedown", "ctrl-b", "ctrl-f",
    "ctrl-u", "ctrl-d", "0", "$", "home", "end", "^", "g", "G", "{", "}", "w", "b", "e", "W", "B",
    "E", "v", "space", "V", "q", "escape", "y", "enter", "/", "a", "i", "au", "aa", "ii", "i{",
    "a{",
];

fn transition(mode: Mode, key: &'static str) -> Option<Action> {
    use Mode::*;
    let direction = match key {
        "a" | "i" if mode != Move => return Some(Action(mode, "prefix", key)),
        "au" | "aa" | "ii" | "i{" | "a{" if mode != Move => {
            return Some(Action(Visual, "object", key));
        }
        "h" | "left" => "left",
        "j" | "down" => "down",
        "k" | "up" => "up",
        "l" | "right" => "right",
        "pageup" | "ctrl-b" => "page_up",
        "pagedown" | "ctrl-f" => "page_down",
        "ctrl-u" => "half_up",
        "ctrl-d" => "half_down",
        "0" | "home" => "line_start",
        "g" => "home",
        "G" => "end",
        "$" | "end" | "^" | "{" | "}" | "w" | "b" | "e" | "W" | "B" | "E" => {
            let motion = match key {
                "$" | "end" => "$",
                _ => key,
            };
            return Some(Action(mode, "text", motion));
        }
        "v" | "space" => return Some(Action(Visual, "anchor", "")),
        "V" => return Some(Action(Line, "anchor_line", "")),
        "q" | "escape" => return Some(Action(mode, "cancel", "")),
        "y" | "enter" if mode != Move => return Some(Action(mode, "yank", "")),
        "y" | "enter" => return Some(Action(mode, "cancel", "")),
        "/" => return Some(Action(mode, "search", "")),
        _ => return None,
    };
    Some(Action(mode, "move", direction))
}

fn main() -> io::Result<()> {
    let mut out = io::stdout().lock();
    writeln!(
        out,
        "// Generated by cargo run --quiet. Edit src/main.rs instead."
    )?;
    writeln!(out, "export const transitions = {{")?;
    for mode in [Mode::Move, Mode::Visual, Mode::Line] {
        writeln!(out, "  {}: {{", name(mode))?;
        for key in KEYS {
            if let Some(Action(next, action, direction)) = transition(mode, key) {
                writeln!(
                    out,
                    "    {key:?}: [{:?}, {action:?}, {direction:?}],",
                    name(next)
                )?;
            }
        }
        writeln!(out, "  }},")?;
    }
    writeln!(out, "}};")
}

fn name(mode: Mode) -> &'static str {
    match mode {
        Mode::Move => "move",
        Mode::Visual => "visual",
        Mode::Line => "line",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use Mode::*;

    #[test]
    fn only_visual_mode_can_yank() {
        assert_eq!(transition(Move, "y"), Some(Action(Move, "cancel", "")));
        assert_eq!(transition(Visual, "y"), Some(Action(Visual, "yank", "")));
    }

    #[test]
    fn motion_extends_only_after_anchoring() {
        assert_eq!(transition(Move, "k"), Some(Action(Move, "move", "up")));
        assert_eq!(transition(Move, "v"), Some(Action(Visual, "anchor", "")));
        assert_eq!(transition(Visual, "k"), Some(Action(Visual, "move", "up")));
    }

    #[test]
    fn linewise_mode_moves_by_rows_and_can_yank() {
        assert_eq!(transition(Move, "V"), Some(Action(Line, "anchor_line", "")));
        assert_eq!(transition(Line, "j"), Some(Action(Line, "move", "down")));
        assert_eq!(transition(Line, "h"), Some(Action(Line, "move", "left")));
        assert_eq!(transition(Line, "y"), Some(Action(Line, "yank", "")));
    }

    #[test]
    fn text_motions_use_the_same_policy_with_or_without_an_anchor() {
        for mode in [Move, Visual, Line] {
            for key in ["w", "b", "e", "W", "B", "E", "{", "}", "^", "$"] {
                assert_eq!(transition(mode, key), Some(Action(mode, "text", key)));
            }
            assert_eq!(
                transition(mode, "ctrl-u"),
                Some(Action(mode, "move", "half_up"))
            );
        }
    }

    #[test]
    fn text_objects_require_visual_mode() {
        for key in ["a", "i"] {
            assert_eq!(transition(Move, key), None);
            for mode in [Visual, Line] {
                assert_eq!(transition(mode, key), Some(Action(mode, "prefix", key)));
            }
        }
        for key in ["au", "aa", "ii", "a{", "i{"] {
            assert_eq!(transition(Move, key), None);
            for mode in [Visual, Line] {
                assert_eq!(transition(mode, key), Some(Action(Visual, "object", key)));
            }
        }
    }
}
