use std::io::{self, Write};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Mode {
    Move,
    Visual,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct Action(Mode, &'static str, &'static str);

const KEYS: &[&str] = &[
    "h", "j", "k", "l", "left", "down", "up", "right", "pageup", "pagedown", "ctrl-b", "ctrl-f",
    "0", "$", "home", "end", "g", "G", "v", "space", "q", "escape", "y", "enter", "/",
];

fn transition(mode: Mode, key: &str) -> Option<Action> {
    use Mode::*;
    let direction = match key {
        "h" | "left" => "left",
        "j" | "down" => "down",
        "k" | "up" => "up",
        "l" | "right" => "right",
        "pageup" | "ctrl-b" => "page_up",
        "pagedown" | "ctrl-f" => "page_down",
        "0" | "home" => "line_start",
        "$" | "end" => "line_end",
        "g" => "home",
        "G" => "end",
        "v" | "space" => return Some(Action(Visual, "anchor", "")),
        "q" | "escape" => return Some(Action(mode, "cancel", "")),
        "y" | "enter" if mode == Visual => return Some(Action(mode, "yank", "")),
        "y" | "enter" => return Some(Action(mode, "cancel", "")),
        "/" => return Some(Action(mode, "search", "")),
        _ => return None,
    };
    Some(Action(
        mode,
        if mode == Move { "move" } else { "extend" },
        direction,
    ))
}

fn main() -> io::Result<()> {
    let mut out = io::stdout().lock();
    writeln!(
        out,
        "// Generated by cargo run --quiet. Edit src/main.rs instead."
    )?;
    writeln!(out, "export const transitions = {{")?;
    for mode in [Mode::Move, Mode::Visual] {
        writeln!(out, "  {}: {{", name(mode))?;
        for key in KEYS {
            if let Some(Action(next, action, direction)) = transition(mode, key) {
                writeln!(
                    out,
                    "    {key:?}: [{:?}, {action:?}, {direction:?}],",
                    name(next)
                )?;
            }
        }
        writeln!(out, "  }},")?;
    }
    writeln!(out, "}};")
}

fn name(mode: Mode) -> &'static str {
    match mode {
        Mode::Move => "move",
        Mode::Visual => "visual",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use Mode::*;

    #[test]
    fn only_visual_mode_can_yank() {
        assert_eq!(transition(Move, "y"), Some(Action(Move, "cancel", "")));
        assert_eq!(transition(Visual, "y"), Some(Action(Visual, "yank", "")));
    }

    #[test]
    fn motion_extends_only_after_anchoring() {
        assert_eq!(transition(Move, "k"), Some(Action(Move, "move", "up")));
        assert_eq!(transition(Move, "v"), Some(Action(Visual, "anchor", "")));
        assert_eq!(
            transition(Visual, "k"),
            Some(Action(Visual, "extend", "up"))
        );
    }
}
